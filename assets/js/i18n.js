  let lang = localStorage.getItem("bhvote.lang") || "en";
  if (!LANGS[lang]) lang = "en";

  function t(key, fallback) {
    const d = LANGS[lang].dict;
    return d[key] || en[key] || fallback || key;
  }

  function setLang(next) {
    if (!LANGS[next]) return;
    lang = next;
    localStorage.setItem("bhvote.lang", next);
    document.documentElement.lang = next;
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  function apply(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"), el.textContent);
    });
    (root || document).querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"), el.getAttribute("placeholder")));
    });
  }

  document.documentElement.lang = lang;
  window.I18N = { t, setLang, apply, get lang() { return lang; }, LANGS };
